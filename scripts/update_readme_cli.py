#!/usr/bin/env python3
"""Regenerate the command table in README.md from the argument parser in ``cli.py``.

    python scripts/update_readme_cli.py           # rewrite the table
    python scripts/update_readme_cli.py --check   # exit 1 when it differs (tests/test_readme.py)
"""
from __future__ import annotations

import argparse
import sys
from collections.abc import Iterator
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

START = "<!-- cli:start (generated by scripts/update_readme_cli.py) -->"
END = "<!-- cli:end -->"


def commands(parser: argparse.ArgumentParser, prefix: str = "ai-audit") -> Iterator[tuple[str, str]]:
    """(command, help) for every subcommand, parents before their children."""
    for action in parser._actions:
        if not isinstance(action, argparse._SubParsersAction):
            continue
        helps = {a.dest: a.help or "" for a in action._choices_actions}
        for name, sub in action.choices.items():
            yield f"{prefix} {name}", helps.get(name, "")
            yield from commands(sub, f"{prefix} {name}")


def table() -> str:
    from cli import _build_parser

    rows = [f"| `{cmd}` | {' '.join(text.split()).replace('|', chr(92) + '|')} |"
            for cmd, text in commands(_build_parser())]
    return "\n".join(["| Command | What it does |", "|---|---|", *rows])


def render(readme: str) -> str:
    """*readme* with the generated table between its markers; ValueError when they are missing."""
    before, start, rest = readme.partition(START)
    _, end, after = rest.partition(END)
    if not start or not end:
        raise ValueError(f"README.md needs {START} and {END}")
    return f"{before}{START}\n{table()}\n{END}{after}"


def main() -> int:
    path = ROOT / "README.md"
    old = path.read_text(encoding="utf-8")
    new = render(old)
    if "--check" in sys.argv[1:]:
        if new != old:
            print("README.md commands differ from cli.py: run python scripts/update_readme_cli.py", file=sys.stderr)
        return int(new != old)
    path.write_text(new, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
