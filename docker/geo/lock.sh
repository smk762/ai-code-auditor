#!/usr/bin/env bash
# Resolve geo.yml into geo-linux-64.lock (exact URLs and md5) inside a throwaway container.
set -euo pipefail
cd "$(dirname "$0")"
docker run --rm -v "$PWD":/env -w /env debian:trixie-slim bash -ec '
  apt-get update -qq >/dev/null && apt-get install -y -qq --no-install-recommends ca-certificates bzip2 curl >/dev/null 2>&1
  export MAMBA_ROOT_PREFIX=/opt/mamba
  curl -fsSL https://micro.mamba.pm/api/micromamba/linux-64/2.3.3 | tar -xj -C /usr/local bin/micromamba
  micromamba create -y -q -p /opt/geo -f geo.yml >/dev/null
  { echo "# Generated by docker/geo/lock.sh from geo.yml. Do not edit by hand."
    micromamba env export -p /opt/geo --explicit --md5 | grep -v "^#"; } > geo-linux-64.lock
  chown '"$(id -u):$(id -g)"' geo-linux-64.lock'
echo "wrote docker/geo/geo-linux-64.lock ($(grep -c '^https' geo-linux-64.lock) packages)"
